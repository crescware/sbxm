/// 文字キーで候補を絞り込めるか。
///
/// 案件の一覧のように候補が多く、識別子を打てば狭まる一覧では`Typed`にする。yes/noや
/// 言語選択のような固定の短い選択肢では`None`にし、入力欄を出さない。どちらにするかは
/// 何を並べるかを知る呼び出し側が決め、promptは候補の数から推測しない。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Filter {
    /// 空白と制御文字を除く打鍵を絞り込み文字列へ足し、一致する候補だけを見せる。
    Typed,
    /// 文字キーを受け付けない。
    None,
}
